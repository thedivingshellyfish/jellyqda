# Blind copy for a second coder (R/intercoder_copy.R)

test_that("qda_intercoder_copy(): same documents, segments and codes, no codings", {
  pa <- new_project(); on.exit(qda_close(), add = TRUE)
  qda_import(transcript_file(turns = 8), segments = "speaker")
  qda_code_add("Beruf"); qda_code_add("KMU", parent = "Beruf")
  qda_code_guide("KMU", definition = "Kleine Firma", rule = "nur explizit")
  qda_code(1, "KMU", segment = 2, memo = "geheim")
  qda_memo_add("Definition KMU", code = "KMU")
  qda_memo_add("Interpretation, nicht weitergeben")
  pb <- file.path(dirname(pa), "b.jellyqda")
  out <- qda_intercoder_copy(pb)
  expect_equal(normalizePath(out), normalizePath(pb))
  expect_error(qda_intercoder_copy(pb), "exists")
  expect_error(qda_intercoder_copy(pa), "active project")
  n_seg <- nrow(jellyqda:::.segments_for(1))
  expect_equal(nrow(qda_codings()), 1)                       # A unchanged
  expect_true("intercoder_copy" %in% qda_events()$action)
  qda_close()
  qda_open(pb)
  expect_equal(nrow(qda_codings()), 0)
  expect_equal(qda_codes()$path, c("Beruf", "Beruf / KMU"))
  expect_equal(qda_codes()$coding_rule[2], "nur explizit")
  expect_equal(nrow(jellyqda:::.segments_for(1)), n_seg)
  m <- qda_memos()
  expect_equal(nrow(m), 1); expect_equal(m$kind, "code")
  ev <- qda_events()
  expect_false(any(grepl("geheim", ev$details, fixed = TRUE)))
  expect_equal(ev$action[1], "intercoder_copy")
  expect_null(qda_history()$undo)                            # nothing to undo in the copy
  # the removed rows are not left in the file
  raw <- readBin(pb, "raw", file.info(pb)$size)
  qda_close()
  expect_false(length(grepRaw(charToRaw("Interpretation, nicht"), raw)) > 0)
  qda_open(pa)
})
