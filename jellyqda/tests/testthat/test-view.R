test_that("qda_view renders numbered segments and colored codings as HTML", {
  new_project()
  on.exit(qda_close(), add = TRUE)
  qda_import(ext("interview_01.txt"))
  qda_code_add("Werdegang", color = "#FF0000")
  qda_code(1, segment = 2, code = "Werdegang")
  html <- qda_view(1, open = FALSE)
  expect_type(html, "character")
  expect_true(grepl("Segment 1", html, fixed = TRUE))
  expect_true(grepl("Segment 4", html, fixed = TRUE))
  expect_true(grepl("<mark", html, fixed = TRUE))
  expect_true(grepl("#FF0000", html, fixed = TRUE))
  expect_true(grepl("interview_01.txt", html, fixed = TRUE))
  # HTML-escaping: no raw unescaped umlaut issues, text is present
  expect_true(grepl("Projektleiterin", html, fixed = TRUE))
})
